- Công dụng.
- Liều dùng.
- Cách sử dụng.
- Những lưu ý quan trọng.
- Khi nào nên quay lại hoặc đi khám.

---

## Bước 4 – Bán hàng trên Novixa

Thực hiện theo các bước:

1. Tìm hoặc tạo thông tin khách hàng (khi khách đồng ý).
2. Quét mã vạch hoặc tìm sản phẩm.
3. Kiểm tra:
   - Đúng thuốc.
   - Đúng hàm lượng.
   - Đúng số lượng.
   - Đúng đơn giá.
4. Kiểm tra lô thuốc theo nguyên tắc **FEFO**.

Novixa sẽ ưu tiên gợi ý lô có hạn sử dụng gần hơn nhưng vẫn đảm bảo chất lượng.

