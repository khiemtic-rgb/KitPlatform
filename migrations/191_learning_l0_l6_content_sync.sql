## Mục tiêu

Sau khi hoàn thành bài học này, bạn sẽ có thể:

- Điều hành một ca làm việc hiệu quả.
- Phân công công việc phù hợp với từng thành viên.
- Hỗ trợ và hướng dẫn nhân viên trong quá trình làm việc.
- Xử lý các tình huống phát sinh đúng thẩm quyền.
- Theo dõi chất lượng phục vụ và kết quả của ca làm việc.
- Hoàn thành báo cáo và bàn giao ca đầy đủ.

---

## Vì sao bài học này quan trọng?

Ca trưởng không phải là người làm nhiều việc nhất.

Ca trưởng là người giúp cả đội làm việc hiệu quả hơn.

Một ca làm việc thành công không phụ thuộc vào một cá nhân, mà phụ thuộc vào sự phối hợp của cả đội.

Vai trò của Ca trưởng là tạo điều kiện để mọi người hoàn thành tốt công việc của mình.

