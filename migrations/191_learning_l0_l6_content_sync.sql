## Bước 1 – Chuẩn bị trước ca

Trước khi bắt đầu ca làm việc, hãy kiểm tra:

- Nhân sự có mặt đầy đủ.
- Lịch làm việc.
- Thiết bị.
- Các công việc cần thực hiện.
- Những cảnh báo quan trọng.
- Hàng hóa cần theo dõi.

Nếu phát hiện vấn đề, hãy xử lý ngay hoặc báo quản lý.

---

## Bước 2 – Phân công công việc

Hãy giao đúng người cho đúng việc.

Ví dụ:

- Nhân viên có kinh nghiệm → quầy tư vấn.
- Nhân viên mới → quầy bán hàng đơn giản hoặc hỗ trợ.
- Người có kinh nghiệm xử lý khách hàng → tiếp nhận các tình huống khó.

Mục tiêu là giúp cả đội làm việc hiệu quả nhất.

---

## Bước 3 – Theo dõi trong ca

Trong suốt ca làm việc, Ca trưởng cần:

- Theo dõi tiến độ công việc.
- Quan sát chất lượng phục vụ.
- Kiểm tra các checklist.
- Theo dõi doanh thu.
- Chủ động phát hiện vấn đề.

Đừng chờ sự cố xảy ra mới xử lý.

---

## Bước 4 – Hỗ trợ và huấn luyện

Một Ca trưởng tốt luôn đồng hành cùng nhân viên.

Hãy:

- Quan sát.
- Góp ý.
- Hướng dẫn.
- Khích lệ.
- Ghi nhận những điểm làm tốt.

Không nên:

- Phê bình nhân viên trước mặt khách.
- Tranh cãi tại quầy.
- Bỏ mặc nhân viên mới.

---

## Bước 5 – Xử lý tình huống

Trong ca làm việc có thể xảy ra:

- Khiếu nại của khách hàng.
- Thiếu hàng.
- Sai giá bán.
- Thiết bị gặp sự cố.
- Nhân viên nghỉ đột xuất.
- Khách đông bất thường.

Khi gặp tình huống:

1. Bình tĩnh.
2. Đánh giá mức độ.
3. Phân công người xử lý.
4. Báo quản lý khi vượt thẩm quyền.
5. Ghi nhận nếu cần.

---

## Bước 6 – Kiểm soát chất lượng

Ca trưởng cần đảm bảo:

- Khách hàng được chào hỏi.
- Nhân viên tư vấn đúng quy trình.
- Thuốc được xuất theo FEFO.
- Checklist được hoàn thành.
- Không có thuốc quá hạn trên quầy.
- Khiếu nại được xử lý kịp thời.

---

## Bước 7 – Theo dõi kết quả

Doanh thu là một chỉ số quan trọng, nhưng không phải là tất cả.

Hãy theo dõi:

- Số lượng hóa đơn.
- Giá trị trung bình mỗi hóa đơn.
- Khách hàng quay lại.
- Chất lượng phục vụ.
- Mức độ hoàn thành công việc.

Nếu kết quả chưa tốt, hãy tìm nguyên nhân trước khi đưa ra kết luận.

---

## Bước 8 – Báo cáo và bàn giao

Kết thúc ca làm việc, hãy tổng hợp:

- Doanh thu.
- Tiền mặt theo quy định.
- Công việc đã hoàn thành.
- Công việc còn tồn.
- Hàng hóa cần theo dõi.
- Các sự cố phát sinh.
- Nội dung bàn giao cho ca sau.

Một báo cáo đầy đủ sẽ giúp ca tiếp theo tiếp tục công việc thuận lợi.

