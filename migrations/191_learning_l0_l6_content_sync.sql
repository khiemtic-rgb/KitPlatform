Các tiêu chí đánh giá gồm:

- Thái độ phục vụ.
- Khả năng lắng nghe.
- Xác định đúng nhu cầu.
- Tư vấn phù hợp.
- Hướng dẫn sử dụng thuốc đầy đủ.
- Không tư vấn vượt phạm vi chuyên môn.
- Chăm sóc khách hàng sau bán.

Hoàn thành từ **80% tiêu chí trở lên** sẽ được xác nhận đã áp dụng thành công tại quầy.

