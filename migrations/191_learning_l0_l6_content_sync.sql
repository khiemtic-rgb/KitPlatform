## Bước 1 – Tiếp đón khách hàng

Hãy tạo ấn tượng tốt ngay từ những giây đầu tiên.

Bạn nên:

- Mỉm cười.
- Giao tiếp bằng mắt.
- Chủ động chào khách.

Ví dụ:

> "Em chào anh/chị. Em có thể hỗ trợ gì cho mình ạ?"

Nếu đang phục vụ khách khác:

> "Anh/chị vui lòng chờ em khoảng 1 phút nhé."

### Không nên

- Không phản hồi khi khách bước vào.
- Vừa phục vụ vừa dùng điện thoại.
- Để khách chờ mà không giải thích.

---

## Bước 2 – Lắng nghe và xác định nhu cầu

Đừng vội giới thiệu thuốc.

Hãy dành thời gian tìm hiểu tình trạng của khách.

Ví dụ:

- Anh/chị đang gặp vấn đề gì?
- Triệu chứng xuất hiện từ khi nào?
- Đã sử dụng thuốc nào chưa?
- Có dị ứng thuốc không?
- Đang điều trị bệnh nào khác không?

Nếu vấn đề vượt ngoài phạm vi tư vấn của bạn, hãy mời dược sĩ phụ trách hỗ trợ.

